// Runs after `npm install`. Replaces the file:../.. link to the repo with the package
// as npm would publish it (`npm pack` of the repo root), so the app builds from the
// published files and autolinking sees exactly what users get. Also writes the test
// fixtures the self-test needs as a JS module (React Native has no file system API).
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(app, '..', '..');

if (!existsSync(join(repo, 'dist', 'entry-react-native.js'))) {
  console.error('lz4-js is not built. In the repo root, run `npm run build:wasm && npm run build:ts` first.');
  process.exit(1);
}

const tmp = mkdtempSync(join(tmpdir(), 'lz4-js-pack-'));
try {
  const packed = JSON.parse(execFileSync('npm', ['pack', '--json', '--pack-destination', tmp], { cwd: repo, encoding: 'utf8' }));
  const tarball = join(tmp, packed[0].filename);
  const target = join(app, 'node_modules', '@kodespire', 'lz4-js');
  // Remove the link itself, never what it points to.
  if (existsSync(target) && lstatSync(target).isSymbolicLink()) unlinkSync(target);
  else rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  execFileSync('tar', ['-xzf', tarball, '-C', target, '--strip-components=1']);
  console.log(`installed ${packed[0].filename} (${packed[0].entryCount} files, ${packed[0].size} bytes packed)`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const fixtures = ['corpus.txt', 'corpus.hc12.lz4', 'corpus.multi.lz4', 'corpus.legacy.lz4', 'dict.bin', 'record.json', 'record.dict.lz4'];
const entries = fixtures.map((name) => {
  const base64 = readFileSync(join(repo, 'test', 'fixtures', name)).toString('base64');
  return `  ${JSON.stringify(name)}: ${JSON.stringify(base64)},`;
});
writeFileSync(
  join(app, 'selftest', 'fixtures.generated.js'),
  `// Generated by scripts/prepare.mjs from test/fixtures (base64). Do not edit.\nexport default {\n${entries.join('\n')}\n};\n`,
);
